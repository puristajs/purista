#!/usr/bin/env node

import { createHash } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const root = process.cwd()
const apiPath = resolve(root, 'web/src/generated/purista-api.json')
const outputPath = resolve(root, 'skills/purista/references/generated-api-index.md')
const check = process.argv.includes('--check')

if (!existsSync(apiPath)) {
	process.stderr.write(`TypeDoc JSON was not found at ${apiPath}\n`)
	process.exit(2)
}

const docs = JSON.parse(readFileSync(apiPath, 'utf8'))
const targets = new Set([
	'ServiceBuilder',
	'CommandDefinitionBuilder',
	'SubscriptionDefinitionBuilder',
	'StreamDefinitionBuilder',
	'QueueDefinitionBuilder',
	'QueueWorkerBuilder',
	'AgentQueueBuilder',
	'SchedulerBuilder',
	'SchedulerRuntime',
	'DefaultSchedulerProvider',
	'createArchitectureManifest',
	'validateArchitectureManifest',
	'ServiceObservabilityContext',
	'exportServiceDefinitions',
	'exportScheduleManifest',
])

const kinds = new Map([
	[32, 'variable'],
	[64, 'function'],
	[128, 'class'],
	[256, 'interface'],
	[2097152, 'type'],
])

const text = parts =>
	(parts ?? [])
		.map(part => part.text ?? part.code ?? '')
		.join('')
		.replace(/\s+/g, ' ')
		.trim()

const sourceOf = node => {
	const source = node.sources?.[0] ?? node.signatures?.[0]?.sources?.[0]
	return source ? `${source.fileName}:${source.line}` : 'generated declaration'
}

const matches = []
const walk = (node, packageName = docs.name) => {
	const currentPackage = node.kind === 2 ? node.name : packageName
	if (currentPackage === '@purista/core' && targets.has(node.name) && kinds.has(node.kind)) {
		matches.push({
			name: node.name,
			kind: kinds.get(node.kind),
			summary: text(node.comment?.summary ?? node.signatures?.[0]?.comment?.summary) || 'No TypeDoc summary available.',
			source: sourceOf(node),
		})
	}
	for (const child of node.children ?? []) {
		walk(child, currentPackage)
	}
}

walk(docs)
const entries = matches.sort((left, right) => left.name.localeCompare(right.name))
const missing = [...targets].filter(target => !entries.some(entry => entry.name === target)).sort()
const digest = createHash('sha256').update(JSON.stringify(entries)).digest('hex').slice(0, 16)

const lines = [
	'# Generated Core API Index',
	'',
	'<!-- generated by scripts/generate-agent-api-knowledge.mjs; do not edit manually -->',
	`<!-- typedoc-digest: ${digest} -->`,
	'',
	'This compact index is derived from current TypeDoc output. It is an API lookup aid, not architecture guidance; follow the canonical skill references for ownership and distributed-system decisions.',
	'',
	'| API | Kind | Verified purpose | Declaration source |',
	'| --- | --- | --- | --- |',
	...entries.map(
		entry => `| \`${entry.name}\` | ${entry.kind} | ${entry.summary.replaceAll('|', '\\|')} | \`${entry.source}\` |`,
	),
	'',
	'## Generation contract',
	'',
	'- Regenerate after TypeDoc/API changes with `npm run generate:agent-api-knowledge`.',
	'- Verify parity in CI with `npm run audit:agent-api-knowledge`.',
	'- Missing selected entries are a generator failure, never a reason to invent a replacement API.',
	'',
]

if (missing.length) {
	process.stderr.write(`Generated API knowledge is missing selected public API entries: ${missing.join(', ')}\n`)
	process.exit(1)
}

const output = lines.join('\n')
if (check) {
	if (!existsSync(outputPath) || readFileSync(outputPath, 'utf8') !== output) {
		process.stderr.write('Generated agent API knowledge is stale. Run npm run generate:agent-api-knowledge.\n')
		process.exit(1)
	}
	process.stdout.write('Generated agent API knowledge is current.\n')
	process.exit(0)
}

writeFileSync(outputPath, output, 'utf8')
process.stdout.write(`Generated ${outputPath}\n`)
